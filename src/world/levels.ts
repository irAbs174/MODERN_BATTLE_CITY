export const getLevel = (id: number): LevelDef => LEVELS.find((l) => l.id === id) ?? LEVELS[0];
export const levelsForWorld = (world: number): LevelDef[] => LEVELS.filter((l) => l.world === world);

/** Difficulty scaling curve applied per stage (composition matters more than raw HP). */
export const stageScaling = (stageId: number) => {
  const t = Math.max(0, stageId - 1);
  return {
    hp: 1 + t * 0.055,
    damage: 1 + t * 0.05,
    speed: 1 + Math.min(0.22, t * 0.014),
    rate: 1 + Math.min(0.5, t * 0.03),
    score: 1 + t * 0.06,
  };
};
