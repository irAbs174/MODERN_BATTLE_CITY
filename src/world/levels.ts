/**
 * Level authoring legend (each character = a 2x2 block of 16-unit cells = 32px):
 *   '.' empty   '#' brick   '@' stone   'I' ice   'M' metal
 *   '~' water   'T'/'B' forest   ',' sand   'A' lava
 *   'P' player spawn   'E' enemy spawn   'H' HQ core   'U' power-up node
 */

export interface WaveGroup {
  type: EnemyId;
  count: number;
  /** Seconds between individual spawns inside this group. */
  interval: number;
  /** Preferred spawn point index (-1 = any free). */
  spawn: number;
}

export interface WaveDef {
  index: number;
  delay: number;
  groups: WaveGroup[];
  announce: string;
  powerups?: PowerUpId[];
}

export interface LevelDef {
  id: number;
  name: string;
  subtitle: string;
  world: number;
  theme: ThemeId;
  map: string[];
  waves: WaveDef[];
  boss?: EnemyId;
  parTime: number;
  hazard?: string;
  tip?: string;
  /** Multiplier on enemy stat scaling beyond the world curve. */
  intensity: number;
}

type WaveTuple = [delay: number, groups: Array<[EnemyId, number]>, announce?: string];

const buildWaves = (tuples: WaveTuple[]): WaveDef[] =>
  tuples.map(([delay, groups, announce], i) => ({
    index: i,
    delay,
    groups: groups.map(([type, count], gi) => ({
      type,
      count,
      interval: type === 'scout' ? 0.55 : type === 'fortress' || type === 'colossus' ? 0 : 0.95,
      spawn: gi % 3,
    })),
    announce: announce ?? (i === 0 ? 'HOSTILES INBOUND' : `WAVE ${i + 1}`),
  }));

